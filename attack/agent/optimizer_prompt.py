def _fmt_gates(pr: dict, eps: dict) -> str:
    """Render the per-gate block, marking UNMEASURED gates explicitly.

    An unmeasured gate used to print as `I=None`, and the QA non-A-Evolve path passes only
    {J, k} -- so every `ours` round on WikiTQ/OfficeQA showed `I=None A=None F=None`. The agent
    does not treat that as "unknown"; it reconstructs a story. One round asserted all three gates
    were 1.000 and held its policy unchanged, burning the round while looking like a decision.
    NOT MEASURED must therefore be loud, and the no-inference rule must be stated, not implied.
    """
    def cell(v):
        return "NOT MEASURED" if v is None else str(v)
    missing = [n for n, v in (("I", eps.get("induction")), ("A", eps.get("activation")),
                              ("F", eps.get("following"))) if v is None]
    out = [
        f"per-repeat : I={cell(pr.get('I'))}  A={cell(pr.get('A'))}  F={cell(pr.get('F'))}"
        "   (3/3 = stable failure = structural; 1/3 = variance)",
        f"eps (lower=better): I={cell(eps.get('induction'))}  A={cell(eps.get('activation'))}"
        f"  F={cell(eps.get('following'))}",
    ]
    if missing:
        out.append(
            f"!! GATE{'S' if len(missing) > 1 else ''} {', '.join(missing)} "
            f"{'WERE' if len(missing) > 1 else 'WAS'} NOT MEASURED THIS ROUND. "
            "'NOT MEASURED' means NO "
            "OBSERVATION EXISTS -- it does NOT mean the gate passed. Do NOT state a numeric value "
            "for an unmeasured gate, do NOT infer one from J, and do NOT conclude the chain is "
            "saturated. Diagnose ONLY from artefacts you actually opened; if the evidence cannot "
            "tell you which gate failed, say so and make the smallest edit your evidence supports.")
    return "\n".join(out)


