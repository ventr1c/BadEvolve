"""Agent-optimizer prompt (design B: read-only agent -> structured JSON; deterministic materialize).

The optimizer is a READ-ONLY tool-using agent (Claude Code, tools: Read/Grep/Glob). It reads the
round's evidence itself (per-task solver trajectories, evolved SKILL.md, analysis outputs,
changelog) and emits ONE JSON proposal. A DETERMINISTIC materializer then stamps it into the
injected study tasks (no LLM interprets the JSON): shared r+cues copied verbatim into every task, trigger
sheet + per-task token + binding line generated by the pipeline, per-task designed goldens written.
The agent never edits files.

JSON has two layers:
  shared   : r + cues -- IDENTICAL (verbatim) across all N injected study tasks. r's recurrence is
             Induction's only fuel, so it must not vary per task.
  per_task : per-task designed goldens (delta_i) -- DEGRADATION ONLY (beacon's per-task token is a
             pipeline-generated frozen artifact the optimizer does not design).

Two variants (causal-prior ablation): "minimal" (no mechanism; agent discovers it from evidence)
vs "with_prior" (mechanism FACTS kept -- F-V2-9/12/16 + read-failing-trajectories -- recipe/move
list deleted). They differ ONLY in the per-gate guidance block.

SINGLE-OBJECTIVE BASELINE (`build_single_objective_prompt`, the A1 ablation baseline): the same
agent, the same read-only evidence, the same budget -- but the loss is NOT factored. It sees ONE
aggregate score (joint success J) instead of per-gate eps {I,A,F}, is told nothing about gates, and
is not routed: it revises the single rule `r` freely. Our method's prompt (above) is untouched, so
the two arms differ ONLY in feedback granularity (+ the seed, see gate_factored_agent's
`single_objective`). Keep the two builders separate rather than adding branches to the factored
prompt: an accidental leak of gate structure into the baseline would silently invalidate the
comparison.

GATE-ADVISORY (`build_advisory_prompt`): the third design, and the one the evidence favors. The
gate decomposition is handed over as DIAGNOSIS (all three measured eps, per-repeat spreads, what
each gate means) but NOT as a decision: no binding gate, no argmax routing, no "edit only this one
component" -- the agent chooses which gate to attack and may edit `r` and/or any cue. Motivation
(F-V2-25): the arm that could see the gates but was not routed by them diagnosed the Activation
regression itself and fixed it, while argmax routing spent both rounds on Following and never
touched Activation (in_body 0.0 -> test 0.0). So the useful half of gate factorisation is the dense
per-gate SIGNAL; the fragile half is forcing the edit onto argmax's pick under k-repeat noise.

Writer switch (writer=): "deterministic" (default; materializer copies the spec verbatim) or
"agent" (an optional second writer/diversifier agent expands the spec, e.g. per-task cue
variations). The prompt states which is downstream so the optimizer knows how fully to specify.
"""
