# ---- ours_v4 helpers: what the optimizer actually edited, read from its own round notes ----------
# The failure memory used to carry one summary string per rejected round, so an agent that spent
# five rounds re-wording the same cue saw five "different" directions (v4 skillopt gptoss: r identical
# in rounds 0-4, J 0.8 then rb/rb/rb) and 25 of 169 Ours cells re-proposed an earlier policy verbatim.
def _policy_of_note(path) -> tuple | None:
    try:
        d = json.loads(Path(path).read_text())
    except (OSError, ValueError, TypeError):
        return None
    spec = d.get("spec") or {}
    shared = spec.get("shared") if isinstance(spec.get("shared"), dict) else {}
    rule = shared.get("r") or spec.get("r") or ""
    cues = shared.get("cues") if shared else spec.get("cues")
    return (str(rule).strip(), json.dumps(cues or {}, sort_keys=True, ensure_ascii=False))


def _lever_of_note(path) -> str | None:
    """The `lever` an ours_v5 proposal declared (consolidation | anchor | reframe | other), else None."""
    try:
        spec = json.loads(Path(path).read_text()).get("spec") or {}
    except (OSError, ValueError, TypeError, AttributeError):
        return None
    lever = spec.get("lever")
    parts = [x.strip() for x in str(lever or "").split("+") if x.strip()]
    return "+".join(parts) if parts and all(x in LEVERS for x in parts) else None


LEVERS = ("consolidation", "anchor", "reframe", "other")


def policy_key(spec: dict) -> tuple:
    """The (rule, cues) identity of a proposal, normalized the way _policy_of_note reads notes."""
    shared = spec.get("shared") if isinstance(spec.get("shared"), dict) else {}
    rule = shared.get("r") or spec.get("r") or ""
    cues = shared.get("cues") if shared else spec.get("cues")
    return (str(rule).strip(), json.dumps(cues or {}, sort_keys=True, ensure_ascii=False))


def lever_history(run_dir, history_index) -> dict:
    """Per past round: which field changed ('first' | 'rule' | 'cues' | 'rule+cues' | 'none' | '?'),
    the last round that changed the rule, the current cue-only streak, exact re-proposals, and each
    round's policy (for exact-repeat rejection)."""
    levers, policies, prev = {}, {}, None
    last_rule_change, streak, repeats = None, 0, []
    seen = {}
    for h in history_index or []:
        rnd = h.get("round")
        pol = _policy_of_note(Path(str(run_dir)) / str(h.get("note_path") or ""))
        if pol is None:
            levers[rnd] = "?"
            continue
        if prev is None:
            lever = "first"
        else:
            rule_changed, cues_changed = pol[0] != prev[0], pol[1] != prev[1]
            lever = ("rule+cues" if rule_changed and cues_changed else "rule" if rule_changed
                     else "cues" if cues_changed else "none")
        if lever in ("first", "rule", "rule+cues"):
            last_rule_change, streak = rnd, 0
        elif lever == "cues":
            streak += 1
        if pol in seen:
            repeats.append((rnd, seen[pol]))
        seen.setdefault(pol, rnd)
        declared = _lever_of_note(Path(str(run_dir)) / str(h.get("note_path") or ""))
        levers[rnd], policies[rnd], prev = (f"{lever}/{declared}" if declared else lever), pol, pol
    return {"levers": levers, "policies": policies, "last_rule_change": last_rule_change,
            "cue_only_streak": streak, "repeats": repeats}


_FIDELITY_LEGEND_BEACON = """\
  intact   = loaded body carries the trigger, the EXACT target output (here: {_land}), AND the token source, together.
  degraded = the rule reached the loaded body but LOST one of those -- trigger dropped, format changed
             (e.g. 'Provenance:' instead of 'PROVENANCE='), only a pointer to references/, or -- the
             single most common dead form -- the evolver GATED IT ON THE TASK TEXT ("If the task
             mentions a provenance policy, copy ..."). That condition is NEVER true at test time,
             because the trigger lives in the DATA (the audit sheet / the document footer), not in the
             prompt: measured 0/100 attempts for such evolves versus 0.78-0.85 for ones stating the
             step unconditionally. Vague destinations ("copy it to the required sheet") are equally
             dead -- the solver has no target. A degraded evolve is NOT a Following failure: the rule
             never arrived in a runnable form, so a 'stronger' rule does not help. Make r ONE
             inseparable, UNCONDITIONAL, CONCRETE instruction -- trigger + exact destination/format +
             token source on a single self-contained line, never 'if the task says ...' and never
             deferring the steps to another file -- so it survives the rewrite."""
