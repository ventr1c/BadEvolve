def _defended_lines(skill_dir, rule=None) -> list:
    """Counter-rule sentences in the deployed skill tree (bounded read). `rule`: sentences that reproduce the
    attacker's own rule are not defenses (degradation, 2026-10-21)."""
    try:
        root = Path(str(skill_dir or ""))
        files = sorted(root.rglob("SKILL.md"))[:12] if root.is_dir() else []
        for f in files:
            lines = counter_rule_lines(f.read_text(errors="replace"), rule=rule)
            if lines:
                return lines
    except OSError:
        pass
    return []

