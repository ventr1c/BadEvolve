def _fmt_history(history_index):
    if not history_index:
        return "  (none yet -- this is the first round)"
    return "\n".join(
        f"  r{h['round']} | {h.get('gate')} | eps change: {h.get('eps_delta','?')} | {h.get('note_path','')}"
        for h in history_index)


def _fmt_single_history(history_index):
    """Baseline history: J only -- never the gate or per-gate eps (that is our method's signal)."""
    if not history_index:
        return "  (none yet -- this is the first round)"
    return "\n".join(
        f"  r{h['round']} | J change: {h.get('j_delta','?')} | {h.get('note_path','')}"
        for h in history_index)


def _fmt_advisory_history(history_index, study=False, levers=None):
    """Advisory history: J AND the per-gate movement, but never a 'binding gate' verdict.
    `levers` (ours_v4 only) appends what each round actually edited."""
    if not history_index:
        return "  (no retained history available)" if study else "  (none yet -- this is the first round)"
    lines = []
    for h in history_index:
        tag = " [REJECTED]" if h.get("rejected") else ""
        if h.get("nonimproving") and not h.get("rejected"):
            tag = " [NON-IMPROVING, KEPT]"
        edited = f" | edited: {levers.get(h['round'], '?')}" if levers is not None else ""
        lines.append(f"  r{h['round']}{tag} | {h.get('gate_delta') or h.get('j_delta','?')} | "
                     f"{h.get('note_path','')}{edited}")
    return "\n".join(lines)


def _fmt_lever_summary(lh: dict, history_index) -> str:
    """ours_v4: the lever facts the per-round index does not make obvious."""
    if not history_index:
        return ""
    out = []
    last = lh.get("last_rule_change")
    if last is not None and last != history_index[-1].get("round"):
        out.append(f"- the rule `r` has NOT changed since round {last}; every edit after it touched cues only.")
    if lh.get("cue_only_streak", 0) >= 2:
        out.append(f"- {lh['cue_only_streak']} consecutive cue-only edits. If I did not move across them, the cue "
                   f"wording is not the lever; consider the rule text, its form, or what the trajectories show.")
    for rnd, first in lh.get("repeats", []):
        out.append(f"- round {rnd} re-proposed round {first}'s policy VERBATIM; it was measured once already.")
    return ("# LEVER CHECK (from your own notes)\n" + "\n".join(out) + "\n\n") if out else ""


def _fmt_rejected_memory(history_index, levers=None):
    """Explicit 'do not repeat this' block: every rolled-back round's edit + how it got worse.
    A rejected proposal is a dead end already paid for; the next round must be told what it was so
    it does not re-propose the same losing direction from the same committed state."""
    if any(h.get("study_memory") for h in history_index or []):
        failed = [h for h in history_index if h.get("rejected") or h.get("nonimproving")]
        if not failed:
            return ""
        lines = ["# PRIOR NON-IMPROVING TRIALS"]
        for h in failed:
            decision = "rolled back" if h.get("rejected") else "kept by this arm's acceptance policy"
            lines.append(f"- r{h['round']}: {(h.get('edit_summary') or '?')[:200]}; "
                         f"{h.get('why_worse') or h.get('j_delta')}; {decision}.")
        lines.append("Use the recorded evidence when reconsidering these edits; non-improvement is not proof of intrinsic harm.")
        return "\n".join(lines) + "\n\n"
    rej = [h for h in (history_index or []) if h.get("rejected")]
    if not rej:
        return ""
    lines = ["# ALREADY TRIED AND ROLLED BACK (do NOT repeat these directions)"]
    for h in rej:
        edited = f" [edited: {levers.get(h['round'], '?')}]" if levers is not None else ""
        lines.append(f"- r{h['round']}{edited}: tried \"{(h.get('edit_summary') or '?')[:200]}\" "
                     f"-> {h.get('why_worse') or 'got worse'}; reverted to the last good policy.")
    lines.append("These edits were measured and made things worse; try a DIFFERENT direction.")
    return "\n".join(lines) + "\n\n"


