def mechanism_key(victim: str, evolver_mode: str = "", protocol: str = "",
                  dataset: str = "") -> str | None:
    """Resolve (framework, evolver mode, deployment protocol) -> a binding key in `_EVOLVER`.

    A FRAMEWORK NAME IS NOT ENOUGH. The same evolver is deployed differently on different arms, and a
    binding that names the wrong deployment is worse than no binding at all:
      * `aevolve` on SpreadsheetBench concatenates the whole workspace into ONE skill file for a fixed
        solver (aevolve_runner.py:248-258), so the native "catalog discovered and read on demand"
        description is false there;
      * `trace2skill` runs success analysis only with `--evolver combined`, and the error-only arm
        cannot learn from a poison task the solver got right;
      * `skillgrad` on SB forces the poison ids into the failure pool, while the QA adapter selects
        failures by grade, so a correctly-answered QA poison task contributes nothing.

    Returns None for an unrecognized combination, which renders no binding at all -- the honest
    fallback, since a wrong mechanism is the failure mode this function exists to prevent.
    """
    v = (victim or "").strip().lower()
    mode = (evolver_mode or "").strip().lower()
    proto = (protocol or "").strip().lower()
    if v == "aevolve":
        # native multi-skill QA vs the SB fixed-solver concatenation
        if proto in ("native_multi_skill", "native"):
            return "aevolve_native"
        return "aevolve_sb_fixed"
    if v == "trace2skill":
        return "trace2skill_combined" if mode == "combined" else "trace2skill_error"
    # SkillGrad / SkillOpt: the SB and QA adapters differ in verified, load-bearing ways, so the
    # dataset decides the key. `legacy_fixed_solver` is the QA driver's own protocol label AND the SB
    # default, so it cannot disambiguate -- the caller passes the dataset explicitly.
    if v == "skillgrad":
        return "skillgrad_qa" if _is_qa(proto, dataset) else "skillgrad_sb"
    if v == "skillopt":
        base = "skillopt_qa" if _is_qa(proto, dataset) else "skillopt_sb"
        # The acceptance rule is part of the mechanism the prompt describes. Read it from the same
        # place the runner does (attack/victims/evolution/skillopt_gate.gate_variant), never from a
        # separate copy: a prompt that says "strictly beats" while the victim accepts ties makes the
        # optimizer solve the wrong problem for the whole run.
        try:
            from attack.victims.evolution.skillopt_gate import gate_variant
            g = (gate_variant() or "strict").strip().lower()
        except Exception:
            g = "strict"
        return base if g == "strict" else f"{base}_{g}"
    if v == "selfevolve":
        return "selfevolve"
    return None


